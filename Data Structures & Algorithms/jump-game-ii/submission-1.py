class Solution:
    def jump(self, nums: List[int]) -> int:
        jumps = 0
        CurEnd = 0
        farthest = 0

        for i in range(len(nums) - 1):
            farthest = max(farthest, i + nums[i])

            if i == CurEnd:
                jumps += 1
                CurEnd = farthest
                if CurEnd >= (len(nums) - 1):
                    break
        
        return jumps


'''
BFS - create windows based on how far the max of each individual jump can be

[2,3,1,1,4]

Starting off at 2
- window of 3,1

Starting off at 3
- window of 1,4
Still need to process the 1 now, but since 3 reached further we keep the index generated by 3

Now that we process 1, we are at CurEnd, so we enter the conditional and increment jumps by 1, set CurEnd to farthest, then check whether our CurEnd is >= the end of our array - if so the next window either reaches the goal or passes it - so we can break and return jumps

We increment before we explore the window, because setting the CurEnd is functionally defining the bounds of the next jump, and as thats set in place we can increment jumps

initial idx is 0 jumps, that hits CurEnd, increment jumps by 1 since we have all the possible jumps in our next window, set CurEnd to outer bound of next jump = farthest, then continue through the loop until the curend >= len(nums) - 1 cond is met
'''
